// Rebuilds email-templates-data.js from the monorepo mail templates.
//
//   node emails/sync-email-templates.mjs [path/to/monorepo]
//
// Default monorepo path: ../monorepo (sibling of this repo). Template names,
// subjects and groups live in META below; add a row when a template is added.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const monorepo = resolve(process.argv[2] || join(here, '../../monorepo'));
const dir = join(monorepo, 'functions/src/core/mail/templates');

const VIRAPP_RESULT_SUBJECT = 'Update on Your Virtual Apprenticeship Application';

const META = [
  // [file, group, name, subject, note?]
  ['signup', 'Account', 'Welcome', 'Welcome to KadaKareer'],
  ['reset-password', 'Account', 'Reset password', 'Reset your password'],
  ['coach-application-reminder', 'Account', 'New coach application (internal)', 'New Coach Application: {{email}}', 'Sent to the Koach team, not to the applicant.'],
  ['invitation-new-user', 'Invitations', 'Invitation, new user', "You've Been Invited!"],
  ['invitation-current-user', 'Invitations', 'Invitation, existing user', "You've Been Invited!"],
  ['booking-success', 'Coaching', 'Booking confirmed', 'Your booking was successful!'],
  ['booking-upcoming', 'Coaching', 'Upcoming coaching session', 'You have an upcoming coaching session.', 'Code sends a template named booking-reminder, which has no file. This one is likely the intended match.'],
  ['event-registration-confirmation', 'Events', 'Event registration', "You're registered!"],
  ['event-reminder', 'Events', 'Event reminder', "Hope you're excited—you have a Kada event coming up!"],
  ['virapp-registration', 'VirApp', 'Registration', 'Welcome Aboard! Thank you for registering for the Virtual Apprenticeship Program'],
  ['virapp-enrollment', 'VirApp', 'Enrollment', 'Welcome Aboard! Your Journey Begins with the Virtual Apprenticeship Program'],
  ['virapp-rejected', 'VirApp', 'Rejection', VIRAPP_RESULT_SUBJECT],
  ['virapp-application-accepted', 'VirApp', 'Application accepted', VIRAPP_RESULT_SUBJECT, 'Subject can be overridden by the caller; this is the default.'],
  ['virapp-application-rejected', 'VirApp', 'Application rejected', VIRAPP_RESULT_SUBJECT, 'Subject can be overridden by the caller; this is the default.'],
  ['virapp-invitation', 'VirApp', 'Group invitation', 'Launching Success: Join a Virtual Apprenticeship Group Now!'],
  ['virapp-acceptance', 'VirApp', 'Group invite accepted', 'Your Virtual Apprenticeship group is growing: A kadet just accepted your invite!'],
  ['virapp-decline', 'VirApp', 'Group invite declined', 'Update on Your Virtual Apprenticeship Group Invitation'],
];

const templates = META.map(([file, group, name, subject, note]) => {
  const html = readFileSync(join(dir, file + '.html'), 'utf8');
  const vars = [...new Set([...html.matchAll(/\{\{\s*(\w+)(?:\s*\|\s*safe)?\s*\}\}/g)].map((m) => m[1]))];
  return { id: file, group, name, subject, note: note || '', vars, html };
});

const out =
  '// Generated by sync-email-templates.mjs from the monorepo mail templates. Do not edit by hand.\n' +
  `// Synced: ${new Date().toISOString().slice(0, 10)}\n` +
  `window.EMAIL_TEMPLATES_SYNCED = ${JSON.stringify(new Date().toISOString().slice(0, 10))};\n` +
  `window.EMAIL_TEMPLATES = ${JSON.stringify(templates)};\n`;

writeFileSync(join(here, 'email-templates-data.js'), out);
console.log(`Wrote ${templates.length} templates (${(out.length / 1024).toFixed(0)} KB)`);
